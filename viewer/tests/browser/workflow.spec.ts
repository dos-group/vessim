import { test, expect } from '@playwright/test'

for (const [kind, base] of [['CLI', 'http://localhost:8721/'], ['export', 'http://127.0.0.1:8722/report/']]) {
  test(`${kind}: summaries, grouping, selection, exports, trajectories and mobile`, async ({page}) => {
    const errors: string[] = [], trajectories: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', r => {if (r.url().includes('/trajectory')) trajectories.push(r.url())})
    await page.goto(`${base}?study=comparison`)
    const rows = page.locator('.results-table tbody > tr')
    await expect(rows).toHaveCount(3)
    await expect(page.locator('body')).not.toContainText('Interactive prototype')
    expect(trajectories).toHaveLength(0)
    await page.getByText('Columns', {exact: true}).click()
    await expect(page.getByRole('group', {name:'Simulation settings',exact:true})).toContainText('seed')
    await expect(page.getByRole('group', {name:'Cost',exact:true})).toContainText('annual cost')
    await page.getByText('Columns', {exact: true}).click()
    await page.locator('#select-page').check()
    await expect(page.locator('.selected-row')).toHaveCount(3)
    const download = page.waitForEvent('download')
    await page.getByRole('button', {name:'Export selected',exact:true}).click()
    expect((await download).suggestedFilename()).toBe('comparison-configurations.csv')
    await page.getByRole('button', {name:'Time series',exact:true}).click()
    await expect(page.locator('.time-chart canvas').first()).toBeVisible()
    expect(trajectories).toHaveLength(3)
    await page.screenshot({path:`../results/viewer-release/${kind}-trajectories.png`,fullPage:true})
    await page.locator('#study').selectOption('sampling')
    await expect(rows).toHaveCount(3)
    await expect(page.locator('.heading')).toContainText('9 runs')
    await page.getByText('Columns', {exact: true}).click()
    await expect(page.getByRole('group', {name:'Run inputs',exact:true})).toContainText('seed')
    await page.getByText('Columns', {exact: true}).click()
    await page.getByRole('button', {name:'Individual runs',exact:true}).click()
    await expect(rows).toHaveCount(9)
    await page.getByRole('button', {name:'Configuration summaries',exact:true}).click()
    await page.locator('#select-page').check()
    await page.getByRole('button', {name:'Time series',exact:true}).click()
    await expect(page.locator('.time-chart canvas').first()).toBeVisible()
    await expect(page.getByRole('button', {name:'Configuration summaries',exact:true})).toHaveAttribute('aria-pressed','true')
    await page.locator('#study').selectOption('multi')
    await expect(rows).toHaveCount(3)
    await page.getByText('Columns', {exact: true}).click()
    await expect(page.getByRole('group', {name:'Whole-system results',exact:true})).toBeAttached()
    await expect(page.getByRole('group', {name:'Microgrid results · North',exact:true})).toBeAttached()
    await page.getByText('Columns', {exact: true}).click()
    await page.setViewportSize({width:390,height:844})
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({path:`../results/viewer-release/${kind}-mobile.png`,fullPage:true})
    expect(errors).toEqual([])
  })
  test(`${kind}: 10,000 summary runs and missing recordings`, async ({page}) => {
    const trajectories: string[] = []
    page.on('request', r => {if (r.url().includes('/trajectory')) trajectories.push(r.url())})
    const started = performance.now()
    await page.goto(`${base}?study=large`)
    await expect(page.locator('.heading')).toContainText('10000 runs')
    await page.getByRole('button',{name:'Individual runs',exact:true}).click()
    await expect(page.locator('.results-table tbody > tr')).toHaveCount(50)
    await expect(page.locator('.table-footer')).toContainText('10000 matching runs')
    expect(trajectories).toEqual([])
    console.log(`${kind} 10,000 summaries to visible runs: ${Math.round(performance.now()-started)} ms`)
    await page.locator('#search').fill('run-9999')
    await expect(page.locator('.results-table tbody > tr')).toHaveCount(1)
    await page.locator('#study').selectOption('partial')
    await expect(page.locator('.results-table tbody > tr')).toHaveCount(1)
    await expect(page.locator('#catalog-notice')).toContainText('data issue')
    await page.locator('#select-page').check()
    await page.getByRole('button',{name:'Time series',exact:true}).click()
    await expect(page.locator('main')).toContainText('Recording unavailable')
  })
}
