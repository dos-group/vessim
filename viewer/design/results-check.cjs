const { chromium, expect } = require('@playwright/test')
const fs = require('node:fs')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  const out = path.resolve(__dirname, '../../results/viewer-proposal/screenshots-results')
  fs.mkdirSync(out, { recursive: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    page.setDefaultTimeout(10000)
    const errors = [], csv = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', r => { if (r.url().endsWith('.csv')) csv.push(r.url()) })
    await page.goto('http://127.0.0.1:8715/viewer/design/?study=infrastructure-year&v=analysis-10')
    await expect(page.locator('.results-table tbody tr')).toHaveCount(8)
    await expect(page.getByRole('button', { name: /^Configuration [↑↓↕]/ })).toBeVisible()
    await expect(page.locator('[data-mode], #status, #stat')).toHaveCount(0)
    await expect(page.locator('.study-details')).not.toHaveAttribute('open')
    await page.getByText('Study details', { exact: true }).click()
    await expect(page.locator('.study-details')).toContainText('Synthetic inputs')
    await page.getByText('Study details', { exact: true }).click()
    const headers = () => page.locator('th[data-kind="visible"]')
    const headerKeys = () => headers().evaluateAll(h => h.map(el => el.dataset.orderKey))
    const initial = await headerKeys()
    const energy = initial.find(id => id.includes('energy_produced'))
    const energyHeader = () => headers().filter({ has: page.locator('button').filter({ hasText: /^energy produced/ }) })
    await expect(energyHeader()).toContainText('GWh')
    await page.locator('#search').fill('grid-only')
    await expect(page.locator('.results-table tbody tr')).toHaveCount(1)
    await expect(energyHeader()).toContainText('GWh')
    await page.locator('#search').fill('')
    const dragColumn = async (from, to) => {
      await headers().nth(from).scrollIntoViewIfNeeded()
      const a = await headers().nth(from).boundingBox(), b = await headers().nth(to).boundingBox()
      await page.mouse.move(a.x + a.width / 2, a.y + 15)
      await page.mouse.down()
      await page.mouse.move(b.x + b.width / 2, b.y + 15, { steps: 12 })
      await page.mouse.up()
    }
    await dragColumn(0, 2)
    const reordered = [initial[1], initial[2], initial[0], ...initial.slice(3)]
    expect(await headerKeys()).toEqual(reordered)
    await headers().nth(2).locator('button').focus()
    await page.keyboard.press('Alt+ArrowLeft')
    expect(await headerKeys()).toEqual([initial[1], initial[0], initial[2], ...initial.slice(3)])
    await page.keyboard.press('Alt+ArrowRight')
    expect(await headerKeys()).toEqual(reordered)
    await expect(page.getByRole('button', { name: 'Configuration ↑', exact: true })).toBeVisible()
    await headers().nth(2).locator('button').click()
    await expect(headers().nth(2)).toContainText('↑')
    await headers().nth(2).locator('button').click()
    await expect(headers().nth(2)).toContainText('↓')
    await page.getByText('Columns', { exact: true }).click()
    expect(await page.locator('.column-group legend').allTextContents()).toEqual([
      'Configuration inputs', 'Run inputs', 'Run results', 'Microgrid results · site',
      'Actor results · site · wind', 'Actor results · site · solar', 'Actor results · site · datacenter',
      'Simulation settings',
    ])
    await expect(page.getByRole('group', { name: 'Configuration inputs', exact: true })).not.toContainText('days')
    const settings = page.getByRole('group', { name: 'Simulation settings', exact: true })
    expect(await settings.locator('label').allTextContents()).toEqual(['days', 'step seconds', 'input model version'])
    await page.screenshot({ path: `${out}/columns.png`, fullPage: true })
    await page.getByLabel('Display unit for Microgrid: site energy produced', { exact: true }).selectOption('MWh')
    await expect(energyHeader()).toContainText('MWh')
    await page.getByText('Columns', { exact: true }).click()
    await page.locator('#y').selectOption(energy)
    expect(await page.evaluate(() => window.echarts.getInstanceByDom(document.querySelector('#scatter')).getOption().yAxis[0].name)).toContain('MWh')
    const row = page.locator('.results-table tbody tr').filter({ has: page.locator('[data-select="wind"]') })
    const energyIndex = reordered.indexOf(energy) + 2
    const recorded = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../../results/infrastructure-study/wind/experiment.json')))
    const expected = recorded.metrics.microgrids.site.energy_produced / 1e6
    const actual = Number((await row.locator('td').nth(energyIndex).innerText()).replaceAll(',', ''))
    expect(Math.abs(actual - expected) / expected).toBeLessThan(0.0001)
    for (const id of ['wind', 'mixed', 'grid-only']) await page.locator(`[data-select="${id}"]`).check()
    const rowKeys = () => page.locator('.results-table [data-select]').evaluateAll(rows => rows.map(r => r.dataset.select))
    const beforePin = await rowKeys()
    const selectedKeys = ['wind', 'mixed', 'grid-only']
    const selectedSort = page.getByRole('button', { name: 'Selected first', exact: true })
    await selectedSort.click()
    await expect(selectedSort).toHaveAttribute('aria-pressed', 'true')
    expect(await rowKeys()).toEqual([
      ...beforePin.filter(id => selectedKeys.includes(id)),
      ...beforePin.filter(id => !selectedKeys.includes(id)),
    ])
    await headers().nth(2).locator('button').click()
    expect((await rowKeys()).slice(0, 3).sort()).toEqual([...selectedKeys].sort())
    await page.locator('[data-select="mixed"]').uncheck()
    expect((await rowKeys()).slice(0, 2).sort()).toEqual(['grid-only', 'wind'])
    await page.locator('[data-select="mixed"]').check()
    await selectedSort.click()
    await expect(selectedSort).toHaveAttribute('aria-pressed', 'false')
    await headers().nth(2).locator('button').click()
    expect(await rowKeys()).toEqual(beforePin)
    await selectedSort.click()
    const downloadEvent = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Export selected' }).click()
    const download = await downloadEvent
    expect(download.suggestedFilename()).toBe('infrastructure-year-configurations.csv')
    const exported = fs.readFileSync(await download.path(), 'utf8')
    const firstLine = exported.split('\r\n')[0]
    expect(exported.split('\r\n').slice(1).map(line => line.split(',')[0])).toEqual(['"wind"', '"grid-only"', '"mixed"'])
    expect(firstLine).toContain('energy produced (MWh)')
    expect(firstLine.indexOf('solar kw')).toBeLessThan(firstLine.indexOf('wind kw'))
    expect(csv).toHaveLength(0)
    await page.screenshot({ path: `${out}/results.png`, fullPage: true })
    await expect(page.getByRole('link', { name: /^Compare/ })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Compare', exact: true })).toHaveCount(0)
    await row.locator('[data-run]').click()
    await page.getByText('Configuration and execution', { exact: true }).click()
    await expect(page.locator('details[open] pre').last()).toContainText('wind_kw')
    await expect(page.locator('details[open] pre').last()).toContainText('microgrids')
    expect(csv).toHaveLength(0)
    await page.locator('#results-nav').click()
    await page.evaluate(() => { location.hash = 'compare' })
    await expect(page).toHaveURL(/#results$/)
    await expect(page.locator('.results-table tbody tr')).toHaveCount(8)
    await page.getByRole('button', { name: 'Time series', exact: true }).click()
    expect(await page.locator('[data-order-key]').evaluateAll(chips => chips.map(c => c.dataset.orderKey))).toEqual(['wind', 'grid-only', 'mixed'])
    await expect(page.locator('#main')).not.toContainText(/baseline/i)
    await expect(page.locator('.time-chart canvas')).toHaveCount(1)
    expect(csv).toHaveLength(3)
    await page.locator('#study').selectOption('recorded')
    await expect(page.locator('.results-table tbody tr')).toHaveCount(27)
    await page.getByRole('button', { name: 'Configurations', exact: true }).click()
    await expect(page.locator('#stat')).toBeVisible()
    await page.locator('#stat').selectOption('median')
    await expect(page.locator('.results-table tbody tr')).toHaveCount(9)
    await page.locator('#study').selectOption('infrastructure-year')
    await expect(page.locator('.results-table tbody tr')).toHaveCount(8)
    expect(await headerKeys()).toEqual(reordered)
    await expect(energyHeader()).toContainText('MWh')
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `${out}/mobile.png`, fullPage: true })
    await page.getByText('Columns', { exact: true }).click()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `${out}/columns-mobile.png`, fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.locator('#study').selectOption('fixed')
    await expect(page.locator('.results-table tbody tr')).toHaveCount(22)
    await expect(page.locator('[data-select="c03-r04"]')).toHaveCount(0)
    await expect(page.locator('#status')).toHaveCount(0)
    expect(errors).toEqual([])
    console.log('PASS: selected-first sorting without changing selection/export order, scoped column groups, run configuration details, removed Compare route, completed-only results, column dragging, unit conversion, lazy trajectories, study state, desktop/mobile.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
