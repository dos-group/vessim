const { chromium, expect } = require('@playwright/test')
const fs = require('node:fs')
const path = require('node:path')

;(async () => {
  const browser = await chromium.launch({ channel: 'chrome' })
  const out = path.resolve(__dirname, '../../results/viewer-proposal/screenshots-order')
  fs.mkdirSync(out, { recursive: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    page.setDefaultTimeout(10000)
    const errors = [], csv = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', r => { if (r.url().endsWith('.csv')) csv.push(r.url()) })
    await page.goto('http://127.0.0.1:8715/viewer/design/?study=infrastructure-year&v=analysis-10')
    await expect(page.locator('.results-table tbody tr')).toHaveCount(8)
    for (const name of ['mixed-storage', 'wind', 'grid-only'])
      await page.locator(`[data-select="${name}"]`).check()
    expect(csv).toHaveLength(0)
    await page.getByRole('button', { name: 'Time series', exact: true }).click()
    await expect(page.locator('.time-chart canvas')).toHaveCount(2)
    const order = () => page.locator('[data-order-key]').evaluateAll(items => items.map(i => i.dataset.orderKey))
    const dragTo = async (source, target) => {
      const a = await page.locator(`[data-order-key="${source}"]`).boundingBox()
      const b = await page.locator(`[data-order-key="${target}"]`).boundingBox()
      await page.mouse.move(a.x + 14, a.y + a.height / 2)
      await page.mouse.down()
      await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 12 })
      await page.mouse.up()
    }
    const expectOrder = async names => {
      expect(await order()).toEqual(names)
      await expect(page.locator('#main')).not.toContainText(/baseline/i)
    }
    await expectOrder(['mixed-storage', 'wind', 'grid-only'])
    await dragTo('grid-only', 'wind')
    await expectOrder(['mixed-storage', 'grid-only', 'wind'])
    await dragTo('wind', 'mixed-storage')
    await expectOrder(['wind', 'mixed-storage', 'grid-only'])
    expect(csv).toHaveLength(3)
    await page.screenshot({ path: `${out}/reordered.png`, fullPage: true })
    await expect(page.locator('.time-chart canvas')).toHaveCount(2)
    const series = () => page.evaluate(() =>
      window.echarts.getInstanceByDom(document.querySelector('.time-chart')).getOption().series.map(s => ({ name: s.id, color: s.lineStyle.color }))
    )
    const before = await series()
    expect(before.map(s => s.name)).toEqual(['wind', 'mixed-storage', 'grid-only'])
    await page.evaluate(() => window.echarts.getInstanceByDom(document.querySelector('.time-chart')).dispatchAction({ type: 'dataZoom', start: 40, end: 42 }))
    await dragTo('wind', 'mixed-storage')
    await expectOrder(['mixed-storage', 'wind', 'grid-only'])
    const after = await series()
    expect(after.map(s => s.name)).toEqual(['mixed-storage', 'wind', 'grid-only'])
    for (const s of after) expect(s.color).toBe(before.find(r => r.name === s.name).color)
    expect(await page.evaluate(() => window.echarts.getInstanceByDom(document.querySelector('.time-chart')).getOption().dataZoom[0].start)).toBe(40)
    expect(csv).toHaveLength(3)
    await page.locator('[data-remove-selection="mixed-storage"]').click()
    await expectOrder(['wind', 'grid-only'])
    await page.getByText('Choose runs (2)', { exact: true }).click()
    await page.locator('[data-time-run="mixed-storage"]').check()
    await expectOrder(['wind', 'grid-only', 'mixed-storage'])
    await page.getByText('Choose runs (3)', { exact: true }).click()
    await page.screenshot({ path: `${out}/timeseries.png`, fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `${out}/mobile.png`, fullPage: true })
    await page.locator('[data-order-key="mixed-storage"]').focus()
    await page.keyboard.press('ArrowLeft')
    await expectOrder(['wind', 'mixed-storage', 'grid-only'])
    await page.keyboard.press('ArrowRight')
    await expectOrder(['wind', 'grid-only', 'mixed-storage'])
    const cdp = await page.context().newCDPSession(page)
    const touchSource = await page.locator('[data-order-key="mixed-storage"]').boundingBox()
    const touchTarget = await page.locator('[data-order-key="wind"]').boundingBox()
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: touchSource.x + 14, y: touchSource.y + touchSource.height / 2 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: touchTarget.x + touchTarget.width / 2, y: touchTarget.y + touchTarget.height / 2 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expectOrder(['mixed-storage', 'wind', 'grid-only'])
    await page.locator('[data-order-key="mixed-storage"]').focus()
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('ArrowRight')
    await expectOrder(['wind', 'grid-only', 'mixed-storage'])
    await cdp.detach()
    await page.locator('#results-nav').click()
    await page.getByRole('button', { name: /^Configuration [↑↓↕]$/ }).click()
    const downloadEvent = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Export selected', exact: true }).click()
    const download = await downloadEvent
    const exported = fs.readFileSync(await download.path(), 'utf8')
    expect(exported.split('\r\n').slice(1).map(line => line.split(',')[0])).toEqual(['"wind"', '"grid-only"', '"mixed-storage"'])
    await page.getByRole('button', { name: 'Time series', exact: true }).click()
    await expectOrder(['wind', 'grid-only', 'mixed-storage'])
    await page.locator('#study').selectOption('recorded')
    await expect(page.locator('.results-table tbody tr')).toHaveCount(27)
    await page.locator('#study').selectOption('infrastructure-year')
    await expect(page.locator('.results-table tbody tr')).toHaveCount(8)
    await page.getByRole('button', { name: 'Time series', exact: true }).click()
    await expectOrder(['wind', 'grid-only', 'mixed-storage'])
    await page.locator('[data-remove-selection="wind"]').click()
    await expectOrder(['grid-only', 'mixed-storage'])
    await page.locator('[data-remove-selection="grid-only"]').click()
    await expect(page.locator('[data-order-key]')).toHaveAttribute('data-order-key', 'mixed-storage')
    await page.locator('[data-remove-selection="mixed-storage"]').click()
    await expect(page.locator('[data-order-key]')).toHaveCount(0)
    expect(errors).toEqual([])
    console.log('PASS: selection order, reordering, removal, append, stable colors/zoom, CSV order, sorting, study switching, empty state, desktop/mobile.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
